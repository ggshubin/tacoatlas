// Builds docs/taco-hunt/food-spots-seed.sql from taco-hunt-spots.json.
//
//   node scripts/build-food-spots-seed.mjs
//
// The SQL upserts on id. Re-running it refreshes the descriptive columns
// but never overwrites George's tracking (status, visited_on, planned_for,
// my_note), so it's safe after he has started marking spots.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'docs/taco-hunt/taco-hunt-spots.json');
const OUT = join(root, 'docs/taco-hunt/food-spots-seed.sql');

const KINDS = new Set(['truck', 'restaurant', 'pop-up', 'stand', 'other']);
const STATUSES = new Set(['todo', 'visited', 'needs-info']);
const PRECISIONS = new Set(['address', 'cross-streets', 'name-search', 'nearby']);
const DATE = /^\d{4}-\d{2}-\d{2}$/;

const text = (v) => (v == null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const date = (v) => (v && DATE.test(v) ? `'${v}'` : 'null');
const num = (v) => (Number.isFinite(v) ? String(v) : 'null');
const arr = (a) => (a?.length ? `array[${a.map(text).join(', ')}]::text[]` : `'{}'::text[]`);

function validate(s) {
  const errs = [];
  if (!s.id || !s.name) errs.push('missing id or name');
  if (s.kind && !KINDS.has(s.kind)) errs.push(`bad kind ${s.kind}`);
  if (!STATUSES.has(s.status)) errs.push(`bad status ${s.status}`);
  if (s.geoPrecision && !PRECISIONS.has(s.geoPrecision)) errs.push(`bad geoPrecision ${s.geoPrecision}`);
  if ((s.lat == null) !== (s.lng == null)) errs.push('lat/lng must both be set or both null');
  if (errs.length) throw new Error(`${s.id ?? '?'}: ${errs.join('; ')}`);
}

const { spots, lastSweepAt } = JSON.parse(readFileSync(SRC, 'utf8'));
spots.forEach(validate);

const ids = new Set();
for (const s of spots) {
  if (ids.has(s.id)) throw new Error(`duplicate id ${s.id}`);
  ids.add(s.id);
}

const rows = spots.map((s) => `  (${[
  text(s.id), text(s.name), text(s.where), text(s.addr), text(s.area), text(s.kind),
  text(s.food), text(s.hours), arr(s.by), String(s.by?.length ?? 0), date(s.first),
  text(s.status), date(s.visitedOn), date(s.plannedFor), text(s.notes), text(s.myNote),
  num(s.lat), num(s.lng), text(s.geoPrecision), text(s.geoMatch),
].join(', ')})`);

const sql = `-- Generated by scripts/build-food-spots-seed.mjs from taco-hunt-spots.json. Do not edit by hand.
-- ${spots.length} spots.
begin;

insert into public.food_spots (
  id, name, where_text, addr, area, kind, food, hours, suggested_by, mentions, first_seen,
  status, visited_on, planned_for, notes, my_note, lat, lng, geo_precision, geo_match
) values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name, where_text = excluded.where_text, addr = excluded.addr,
  area = excluded.area, kind = excluded.kind, food = excluded.food, hours = excluded.hours,
  suggested_by = excluded.suggested_by, mentions = excluded.mentions,
  first_seen = excluded.first_seen, notes = excluded.notes,
  lat = excluded.lat, lng = excluded.lng,
  geo_precision = excluded.geo_precision, geo_match = excluded.geo_match;

insert into public.food_spots_meta (id, last_sweep_at)
values ('sweep', ${text(lastSweepAt)})
on conflict (id) do update set last_sweep_at = excluded.last_sweep_at;

commit;
`;

writeFileSync(OUT, sql);
console.log(`Wrote ${spots.length} spots to ${OUT}`);
